# -*- coding: utf-8 -*-
"""兼容入口：附件 mcp_bridge 响应帧 -> 标准 MCP tool result。

保留旧 ``decode_tool_response`` API；底层不再解析 generated protobuf ToolResponse，
而使用附件 ``decodeToolResult`` 直接取得业务字段，再包装为现工程既有 MCP 结果结构。
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from mcp_wire import mcp_bridge
from voice_agent.mcp_http_server.protocol_adapter import mcp_tool_result
from shared_runtime.logging_config import get_logger, log_print

logger = get_logger(__name__)


class ProtoRuntimeError(RuntimeError):
    """保留旧公开异常名；新桥不再依赖 generated protobuf runtime。"""


def decode_tool_response(
    wire_bytes: bytes,
    *,
    request_context: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """使用附件 ``decodeToolResult`` 解码，并保持旧 MCP 包装结构。"""
    try:
        decoded = mcp_bridge.decodeToolResult(wire_bytes)
    except Exception as exc:
        raise ProtoRuntimeError(f"无法解码 mcp_bridge 响应帧: {exc}") from exc

    if decoded is None:
        raise ProtoRuntimeError("mcp_bridge 响应帧为空")
    if isinstance(decoded, list):
        if len(decoded) != 1:
            raise ProtoRuntimeError(
                f"decode_tool_response expects one entry, got {len(decoded)}"
            )
        decoded = decoded[0]
    if not isinstance(decoded, dict):
        raise ProtoRuntimeError("mcp_bridge 返回了非对象响应")

    context = request_context or {}
    request_id = context.get("request_id", decoded.get("id"))
    business = decoded.get("result")
    if not isinstance(business, dict):
        business = {"result": business}
    business.setdefault("code", 0)
    is_error = business.get("code") not in (None, 0, "0")
    return mcp_tool_result(request_id, business, is_error=is_error)


def _cli() -> int:
    parser = argparse.ArgumentParser(description="Decode mcp_bridge response frame to MCP JSON")
    parser.add_argument("input", help="input binary frame file")
    parser.add_argument("--context", help="JSON context generated by mcp_to_proto.py")
    parser.add_argument("-o", "--output", help="output JSON file; omit to stdout")
    args = parser.parse_args()

    context = None
    if args.context:
        context = json.loads(Path(args.context).read_text(encoding="utf-8"))
    result = decode_tool_response(Path(args.input).read_bytes(), request_context=context)
    text = json.dumps(result, ensure_ascii=False, indent=2)
    if args.output:
        Path(args.output).write_text(text, encoding="utf-8")
    else:
        log_print(logger, text)
    return 0


if __name__ == "__main__":
    raise SystemExit(_cli())
